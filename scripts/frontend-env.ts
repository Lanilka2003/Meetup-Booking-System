/**
 * Write ../frontend/.env from the deployed stack outputs.
 *
 *   npm run frontend-env              # refuses to overwrite an existing .env
 *   npm run frontend-env -- --force
 */
import { existsSync, writeFileSync } from 'node:fs';
import * as path from 'node:path';

import { stackOutputs } from './outputs';

async function main() {
  const o = await stackOutputs();
  const target = path.join(__dirname, '..', '..', 'frontend', '.env');
  if (existsSync(target) && !process.argv.includes('--force')) {
    throw new Error(`${target} already exists. Re-run with --force to overwrite.`);
  }
  const contents = [
    '# Generated by backend/scripts/frontend-env.ts from the deployed stack outputs.',
    `EXPO_PUBLIC_COGNITO_USER_POOL_ID=${o.UserPoolId}`,
    `EXPO_PUBLIC_COGNITO_USER_POOL_CLIENT_ID=${o.UserPoolClientId}`,
    `EXPO_PUBLIC_API_BASE_URL=${o.ApiUrl}`,
    'EXPO_PUBLIC_USE_MOCK=false',
    '',
  ].join('\n');
  writeFileSync(target, contents);
  console.log(`✔ Wrote ${target}`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
